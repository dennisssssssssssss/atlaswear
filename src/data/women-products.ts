import {
  calcCompareAtRon,
  calcPriceRon,
  estimateCompareAtRon,
  estimatePriceRon,
} from "@/lib/pricing";

const catalog = (fileName: string) => resolveAssetUrl(`/catalog/${fileName}`);

const color = (
  id: string,
  en: string,
  ro: string,
  hex: string,
): ProductColor => ({
  id,
  name: localize(en, ro),
  hex,
});

type ProductInput = Omit<Product, "audience" | "priceRon" | "compareAtRon"> & {
  audience?: Product["audience"];
  priceRon?: number;
  compareAtRon?: number;
};

const product = (entry: ProductInput): Product => {
  const priceRon =
    entry.priceRon ??
    (entry.costUsd
      ? calcPriceRon(entry.costUsd)
      : estimatePriceRon(entry.brand, entry.category));
  const compareAtRon =
    entry.compareAtRon ??
    (entry.costUsd
      ? calcCompareAtRon(priceRon)
      : estimateCompareAtRon(priceRon));

  return {
    ...entry,
    audience: entry.audience ?? "women",
    priceRon,
    compareAtRon,
  };
};

